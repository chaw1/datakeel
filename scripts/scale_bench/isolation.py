"""Create and destroy only benchmark-owned local files and database schemas."""

from __future__ import annotations

import os
import tempfile
from contextlib import contextmanager
from pathlib import Path
from typing import TYPE_CHECKING
from uuid import uuid4

from sqlalchemy import event, text

from datakeel.storage.database import Database
from scripts.scale_bench.common import check_space
from scripts.scale_bench.models import SCALES, Config, Context

if TYPE_CHECKING:
    from collections.abc import Generator

    from sqlalchemy.engine.interfaces import DBAPIConnection
    from sqlalchemy.pool import ConnectionPoolEntry


def _safe_environment(home: Path) -> None:
    for name in tuple(os.environ):
        if name.startswith(("DATAKEEL_", "LANGCHAIN_", "LANGSMITH_")) and name != (
            "DATAKEEL_TEST_DATABASE_URL"
        ):
            os.environ.pop(name, None)
    for name in ("OPENAI_API_KEY", "ANTHROPIC_API_KEY", "LANGSMITH_API_KEY"):
        os.environ.pop(name, None)
    os.environ["DATAKEEL_HOME"] = str(home)
    os.environ["LANGCHAIN_TRACING_V2"] = "false"
    os.environ["LANGSMITH_TRACING"] = "false"


@contextmanager
def _home_environment(home: Path) -> Generator[None]:
    previous = os.environ.get("DATAKEEL_HOME")
    _safe_environment(home)
    try:
        yield
    finally:
        if previous is None:
            os.environ.pop("DATAKEEL_HOME", None)
        else:
            os.environ["DATAKEEL_HOME"] = previous


def bind_schema(db: Database, schema: str) -> None:
    """Bind future connections to a schema generated by this benchmark invocation."""
    if not schema.startswith("bench_") or not schema.removeprefix("bench_").isalnum():
        message = "Invalid benchmark schema"
        raise ValueError(message)
    db.engine.dispose()

    @event.listens_for(db.engine, "connect")
    def set_schema(connection: DBAPIConnection, _record: ConnectionPoolEntry) -> None:
        cursor = connection.cursor()
        cursor.execute(f'SET search_path TO "{schema}"')
        connection.commit()
        cursor.close()


@contextmanager
def isolated(config: Config) -> Generator[Context]:
    """Run one workload in a fresh schema or SQLite file, and always clean it up."""
    check_space(Path.cwd())
    with (
        tempfile.TemporaryDirectory(prefix="datakeel-bench-") as directory,
        _home_environment(Path(directory)),
    ):
        root = Path(directory)
        url = os.environ.get("DATAKEEL_TEST_DATABASE_URL") if config.stack == "postgres" else None
        if config.stack == "postgres" and not url:
            message = "PostgreSQL requires an explicitly supplied local test database"
            raise ValueError(message)
        db = Database(url or f"sqlite:///{root / 'bench.db'}")
        schema = "bench_" + uuid4().hex if not db.sqlite else None
        if schema:
            if db.engine.url.host not in ("localhost", "127.0.0.1"):
                message = "Benchmark databases must be explicitly authorized loopback instances"
                raise ValueError(message)
            with db.engine.begin() as connection:
                connection.execute(text(f'CREATE SCHEMA "{schema}"'))
            bind_schema(db, schema)
        try:
            db.migrate()
            yield Context(
                config=config, scale=SCALES[config.size], db=db, root=root, schema_name=schema
            )
        finally:
            if schema:
                with db.engine.begin() as connection:
                    connection.execute(text(f'DROP SCHEMA "{schema}" CASCADE'))
            db.engine.dispose()
