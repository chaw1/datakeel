def evidence_bytes(item: EvidenceFile, root: Path) -> bytes:
    """Read only explicitly listed development upstream files inside a dedicated root."""
    relative = Path(item.path)
    if relative.is_absolute() or ".." in relative.parts or not relative.parts:
        msg = "upstream evidence path must be relative"
        raise ValueError(msg)
    candidate = root / relative
    if not candidate.resolve().is_relative_to(root.resolve()):
        msg = "upstream evidence escaped its development root"
        raise ValueError(msg)
    if any(path.is_symlink() for path in (candidate, *candidate.parents)):
        msg = "upstream evidence symlinks are forbidden"
        raise ValueError(msg)
    data = candidate.read_bytes()
    if sha256(data) != item.sha256:
        msg = "upstream evidence hash mismatch"
        raise ValueError(msg)
    return data


def source_blockers(registry: SourceRegistry, root: Path) -> tuple[str, ...]:
    """Check retained evidence and row metadata; never fetch missing public data."""
    blockers: list[str] = []
    for source in registry.sources:
        if source.status == "blocked":
            blockers.extend(f"{source.source_id}: {reason}" for reason in source.blockers)
        for evidence in source.license_evidence:
            if not evidence_bytes(evidence, root).strip():
                msg = "empty upstream license evidence"
                raise ValueError(msg)
        for row in source.rows:
            original = evidence_bytes(row.original_file, root)
            if sha256(original) != row.original_sha256:
                msg = "original row hash mismatch"
                raise ValueError(msg)
            metadata = RowMetadata.model_validate_json(evidence_bytes(row.metadata, root))
            evidence_bytes(metadata.raw_upstream, root)
            _check_metadata(source.source_id, row, metadata)
    return tuple(blockers)


def _check_metadata(source: str, row: PublicRow, metadata: RowMetadata) -> None:
    declared = row.model_dump(mode="json")
    normalized = metadata.model_dump(mode="json")
    for key in ("stable_id", "revision", "license_id", "license_url", "attribution"):
        absent_pd_url = key == "license_url" and row.license_id == "Public-Domain"
        if (not declared[key] and not absent_pd_url) or normalized[key] != declared[key]:
            msg = "upstream metadata does not bind the selected row"
            raise ValueError(msg)
    required = (
        (
            "pageid",
            "revid",
            "imageinfo",
            "extmetadata",
            "original_url",
            "author",
            "license_short_name",
        )
        if source == "wikimedia-commons"
        else (
            "dataset_revision",
            "config",
            "split",
            "row_index",
            "wikidata_id",
            "version_id",
            "original_url",
            "author",
        )
    )
    if any(
        normalized[key] is None
        or normalized[key] == ""
        or normalized[key] == []
        or normalized[key] == {}
        for key in required
    ):
        msg = "upstream metadata incomplete"
        raise ValueError(msg)
    allowed = (
        {"CC0-1.0", "Public-Domain"}
        if source == "wikimedia-commons"
        else {"CC-BY-SA-3.0", "CC-BY-SA-4.0"}
    )
    if row.license_id not in allowed:
        msg = "upstream data license not eligible"
        raise ValueError(msg)


def verify_local() -> Manifest:
    """Check deterministic bytes, schemas, fake wire mappings and group splits."""
    expected = build()
    generated = ROOT / "generated"
    if {p.name for p in generated.iterdir()} != set(expected):
        msg = "generated file set differs"
        raise ValueError(msg)
    for name, data in expected.items():
        if (generated / name).read_bytes() != data:
            msg = "generated bytes differ"
            raise ValueError(msg)
        if name.endswith(".schema.json"):
            Draft202012Validator.check_schema(json.loads(data))
    for schema, path in (
        ("Manifest", generated / "manifest.json"),
        ("WireExample", generated / "fake-wire.json"),
        ("SourceRegistry", ROOT / "sources.json"),
        ("SearchSpace", ROOT / "search-space.json"),
        ("PublicManifest", ROOT / "public-manifest.json"),
        ("LicenseLedger", ROOT / "license-ledger.json"),
    ):
        validator = cast(
            "Validator", Draft202012Validator(json.loads(expected[f"{schema}.schema.json"]))
        )
        validator.validate(json.loads(path.read_bytes()))
    manifest = Manifest.model_validate_json((generated / "manifest.json").read_bytes())
    SearchSpace.model_validate_json((ROOT / "search-space.json").read_bytes())
    if not manifest.assets or split_overlap(manifest.assets):
        msg = "empty or intersecting development groups"
        raise ValueError(msg)
    if split_assets(tuple(reversed(manifest.assets))) != manifest.assets:
        msg = "noncanonical development split"
        raise ValueError(msg)
    _verify_assets(manifest)
    _verify_wire(WireExample.model_validate_json((generated / "fake-wire.json").read_bytes()))
    return manifest


def _verify_assets(manifest: Manifest) -> None:
    originals = {
        asset.original_group: asset.content_sha256
        for asset in manifest.assets
        if asset.variant == "original"
    }
    if {asset.split for asset in manifest.assets} != {"dev_tune", "dev_validation"}:
        msg = "development split missing a partition"
        raise ValueError(msg)
    for asset in manifest.assets:
        payload = base64.b64decode(asset.content_base64, validate=True)
        if sha256(payload) != asset.content_sha256:
            msg = "fixture content hash mismatch"
            raise ValueError(msg)
        if originals.get(asset.original_group) != asset.original_sha256:
            msg = "fixture original hash mismatch"
            raise ValueError(msg)


def _verify_wire(wire: WireExample) -> None:
    text = prepare_text(wire.text_request.input[0], tokenizer="fake-codepoint-v1")
    if text != wire.text_prepared:
        msg = "text preprocessing drift"
        raise ValueError(msg)
    image = wire.image_prepared
    payload = base64.b64decode(image.payload_base64, validate=True)
    if sha256(payload) != image.payload_sha256 or image != prepare_image(payload):
        msg = "image preprocessing drift"
        raise ValueError(msg)
    if wire.image_request.input[0].image != image.data_uri:
        msg = "image data URI mismatch"
        raise ValueError(msg)
    validate_response(wire.text_response, wire.text_request, (text.payload_sha256,))
    validate_response(wire.image_response, wire.image_request, (image.payload_sha256,))


def _public_evidence(
    registry: SourceRegistry,
    blockers: tuple[str, ...],
    public_manifest: PublicManifest | None,
) -> dict[str, object]:
    return {
        "contract_version": "we-e1-v1",
        "kind": "public_development_only",
        "status": "blocked" if blockers else "awaiting_independent_review",
        "acquisition_network_performed": registry.network_performed,
        "sources_registry_sha256": sha256(canonical(registry.model_dump(mode="json"))),
        "development_manifest_sha256": (
            sha256(canonical(public_manifest.model_dump(mode="json"))) if public_manifest else None
        ),
        "license_ledger_sha256": public_manifest.license_ledger_sha256 if public_manifest else None,
        "eligible_public_originals": (
            sum(a.variant == "original" and a.license_eligible for a in public_manifest.assets)
            if public_manifest
            else 0
        ),
        "source_license_validation": "checked_with_blockers" if blockers else "checked",
        "public_rows": [
            row.model_dump(mode="json")
            for source in registry.sources
            if source.status == "frozen" and public_manifest
            for row in source.rows
        ],
        "restricted_candidate_rows": [
            row.model_dump(mode="json")
            for source in registry.sources
            if source.status == "blocked" and public_manifest
            for row in source.rows
        ],
        "blockers": blockers,
    }


def reports(
    manifest: Manifest,
    registry: SourceRegistry,
    blockers: tuple[str, ...],
    public_manifest: PublicManifest | None = None,
) -> dict[str, object]:
    """Export public-development evidence separately; never fabricate independent results."""
    evidence = _public_evidence(registry, blockers, public_manifest)
    return {
        "development-public-evidence.json": evidence,
        "W-E-A1.json": {
            "scope": "E1_local_contract_only",
            "status": "local_checks_passed",
            "independent_acceptance": "pending",
            "network_calls": 0,
            "real_text": "blocked_budget_zero_and_egress_disabled",
            "real_image": "blocked_compatibility_usage_and_budget_unproven",
            "semantic_quality": "not_tested",
            "fake_version": "we-e1-fake-v1",
        },
        "W-E-A9.json": {
            "status": "blocked" if blockers else "pending_independent_intersection",
            "public_baseline_frozen": not blockers,
            "synthetic_fixture_count": len(manifest.assets),
            "development_split_identity_overlap_count": len(split_overlap(manifest.assets)),
            "public_development_split_overlap_count": (
                len(split_overlap(public_manifest.assets)) if public_manifest else None
            ),
            "public_provenance_integrity": "verified" if public_manifest else "not_verified",
            "license_eligible_originals": evidence["eligible_public_originals"],
            "independent_license_review": "pending",
            "development_public_evidence_sha256": sha256(canonical(evidence)),
            "holdout_access": "not_performed",
            "independent_intersection": "not_tested",
            "blockers": blockers,
        },
        "E1-exit.json": {
            "status": "blocked",
            "e2_may_start": False,
            "blockers": (
                *blockers,
                "independent_five_dimension_intersection_and_access_audit_pending",
                "independent_source_license_review_pending",
                "full_CI_gate_pending",
                "independent_session_acceptance_pending",
            ),
            "real_quality": "not_tested",
            "we_overall_complete": False,
        },
    }


def main() -> None:
    """Return 0 for local contracts, or 2 for an explicitly blocked public-data gate."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report-dir", type=Path, default=Path("artifacts/we"))
    parser.add_argument("--public-gate", action="store_true")
    parser.add_argument("--development-root", type=Path)
    args = parser.parse_args()
    manifest = verify_local()
    registry = SourceRegistry.model_validate_json((ROOT / "sources.json").read_bytes())
    public_manifest = None
    if args.development_root is not None:
        public = build_public(args.development_root)
        write_public(public, args.development_root, ROOT, check=True)
        public_manifest = PublicManifest.model_validate_json(
            public.public_files["public-manifest.json"]
        )
        LicenseLedger.model_validate_json(public.public_files["license-ledger.json"])
        blockers = source_blockers(registry, args.development_root)
    else:
        blockers = ("explicit_development_root_required_for_real_public_evidence",)
    args.report_dir.mkdir(parents=True, exist_ok=True)
    for name, value in reports(manifest, registry, blockers, public_manifest).items():
        (args.report_dir / name).write_bytes(canonical(value))
    # Only a different custodian can complete acceptance; this CLI never awards a pass.
    raise SystemExit(2 if args.public_gate else 0)


if __name__ == "__main__":
    main()
