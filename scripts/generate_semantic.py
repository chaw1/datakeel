"""Generate portable language snapshots from the single semantic YAML contract."""

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def generate() -> None:
    """Write deterministic Python/TypeScript snapshots of the YAML contract."""
    contract = yaml.safe_load((ROOT / "contracts/semantic/file-semantics.yaml").read_text())
    serialized = json.dumps(contract, ensure_ascii=False, sort_keys=True, indent=2)
    (ROOT / "datakeel/semantic/_snapshot.json").write_text(serialized + "\n")
    (ROOT / "datakeel/semantic/_snapshot.py").write_text(
        "# Copyright 2026 Datakeel contributors\n"
        "# SPDX-License-Identifier: Apache-2.0\n\n"
        '"""Generated by scripts/generate_semantic.py; edit the YAML contract."""\n\n'
        "import json\nfrom pathlib import Path\nfrom typing import Any\n\n"
        "# Any is confined to the validated semantic contract serialization boundary.\n"
        'CONTRACT: dict[str, Any] = json.loads(Path(__file__).with_suffix(".json").read_text())\n'
    )
    (ROOT / "datakeel/semantic/snapshot.ts").write_text(
        "// Generated by scripts/generate_semantic.py; edit the YAML contract.\n"
        f"export const semanticContract = {serialized} as const;\n"
    )


if __name__ == "__main__":
    generate()
