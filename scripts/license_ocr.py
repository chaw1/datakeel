"""Audit the explicitly selected OCR extra independently of the core license policy."""

from __future__ import annotations

import argparse
import platform
import sys
from pathlib import Path

from packaging.licenses import InvalidLicenseExpression, canonicalize_license_expression
from rich.console import Console

from scripts.license_audit import license_findings, render_notices
from scripts.license_models import LicenseFinding, LicensePackage, LicenseReport
from scripts.license_ocr_evidence import reviewed_ocr_license
from scripts.license_ocr_native import native_findings
from scripts.license_python import python_packages

_OPTIONAL_EXCEPTION = "MPL-2.0 AND MIT"


def ocr_license_findings(package: LicensePackage) -> tuple[LicenseFinding, ...]:
    """Permit only the approved tqdm compound license in the optional OCR installation."""
    if package.ecosystem == "python" and (package.name, package.version) == (
        "onnxruntime",
        "1.31.0",
    ):
        return (
            LicenseFinding(
                ecosystem=package.ecosystem,
                name=package.name,
                version=package.version,
                license="MIT AND MPL-2.0",
                reason=(
                    "The pinned ONNXRuntime CPU wheel contains Eigen code under MPL-2.0. "
                    "The optional tqdm allowance does not cover Eigen. Upstream evidence: "
                    "https://github.com/microsoft/onnxruntime/blob/v1.31.0/ThirdPartyNotices.txt"
                ),
            ),
        )
    try:
        expression = canonicalize_license_expression(package.license)
    except InvalidLicenseExpression:
        return license_findings(package)
    if (
        package.ecosystem == "python"
        and package.name == "tqdm"
        and expression == _OPTIONAL_EXCEPTION
    ):
        return ()
    return license_findings(package)


def audit_ocr(root: Path) -> LicenseReport:
    """Check the locked core-plus-OCR closure and matching installed dependency metadata."""
    packages = tuple(reviewed_ocr_license(item) for item in python_packages(root, extras=("ocr",)))
    return LicenseReport(
        python_target=f"Python {platform.python_version()} / {sys.platform} / {platform.machine()}",
        packages=packages,
        findings=(
            *(finding for package in packages for finding in ocr_license_findings(package)),
            *native_findings(),
        ),
    )


def main() -> None:
    """Run inside an isolated OCR installation and write only explicitly selected artifacts."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path)
    parser.add_argument("--json-report", type=Path)
    args = parser.parse_args()
    report = audit_ocr(args.root)
    if args.output:
        notice = render_notices(report).replace(
            "Generated by `uv run python scripts/license_audit.py`",
            "Generated by `python scripts/license_ocr.py` for the optional OCR extra",
        )
        notice += (
            "\nOptional-only exception: `tqdm` uses `MPL-2.0 AND MIT`. MPL-2.0 is file-level\n"
            "weak copyleft; this optional installation preserves upstream source and notices.\n"
            "The core runtime audit policy does not contain this exception.\n"
        )
        args.output.write_text(notice)
    if args.json_report:
        args.json_report.write_text(report.model_dump_json(indent=2) + "\n")
    console = Console()
    for finding in report.findings:
        console.print(f"FAIL {finding.name}: {finding.reason}", markup=False)
    console.print(
        f"Optional OCR packages: {len(report.packages)}; findings: {len(report.findings)}"
    )
    raise SystemExit(bool(report.findings))


if __name__ == "__main__":
    main()
