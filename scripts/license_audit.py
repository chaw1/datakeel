"""Generate a locked runtime license inventory and fail on unknown or unapproved licenses."""

from __future__ import annotations

import argparse
import platform
import re
import sys
from pathlib import Path

from packaging.licenses import InvalidLicenseExpression, canonicalize_license_expression
from rich.console import Console

from scripts.license_frontend import frontend_packages
from scripts.license_models import LicenseFinding, LicensePackage, LicenseReport
from scripts.license_python import python_packages
from scripts.license_rust import rust_packages

ALLOWED_LICENSES = frozenset(
    {
        "Apache-2.0",
        "MIT",
        "MIT-0",
        "MIT-CMU",
        "CC0-1.0",
        "BSD-2-Clause",
        "BSD-3-Clause",
        "ISC",
        "PSF-2.0",
        "Zlib",
        "OFL-1.1",
        "0BSD",
        "Python-2.0",
        "Unlicense",
    }
)
RUST_ALLOWED_LICENSES = frozenset(
    {"MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "Unicode-DFS-2016", "Unicode-3.0"}
)
PACKAGE_EXCEPTIONS = {
    "certifi": "MPL-2.0",
    "orjson": "MPL-2.0 AND (Apache-2.0 OR MIT)",
    "regex": "Apache-2.0 AND CNRI-Python",
}


def license_findings(package: LicensePackage) -> tuple[LicenseFinding, ...]:
    """Require every SPDX term to be permitted, retaining exact approved package exceptions."""
    try:
        expression = canonicalize_license_expression(package.license)
    except InvalidLicenseExpression:
        reason = "Unknown or invalid SPDX license expression"
    else:
        if package.ecosystem == "rust" and expression == "Apache-2.0 WITH LLVM-exception":
            return ()
        terms = set(re.findall(r"[A-Za-z0-9][A-Za-z0-9.+-]*", expression)) - {"AND", "OR"}
        if package.ecosystem == "python" and PACKAGE_EXCEPTIONS.get(package.name) == expression:
            return ()
        allowed = RUST_ALLOWED_LICENSES if package.ecosystem == "rust" else ALLOWED_LICENSES
        rejected = sorted(terms - allowed)
        if not rejected:
            return ()
        reason = "License terms outside the allowlist: " + ", ".join(rejected)
    return (
        LicenseFinding(
            ecosystem=package.ecosystem,
            name=package.name,
            version=package.version,
            license=package.license,
            reason=reason,
        ),
    )


def audit(root: Path) -> LicenseReport:
    """Collect runtime closures and the complete locked Rust build graph."""
    packages = (*python_packages(root), *frontend_packages(root), *rust_packages(root))
    return LicenseReport(
        python_target=f"Python {platform.python_version()} / {sys.platform} / {platform.machine()}",
        packages=packages,
        findings=tuple(finding for package in packages for finding in license_findings(package)),
    )


def render_notices(report: LicenseReport) -> str:
    """Render reproducible package identities without local paths or upstream personal details."""
    lines = [
        "# Third-party runtime notices",
        "",
        "Generated by `uv run python scripts/license_audit.py` from the locked runtime graph.",
        "",
        f"Python target: {report.python_target}. Python environment markers are evaluated for this",
        "target; all transitively selected extras are included. Development groups are excluded.",
        "The frontend inventory follows production, optional, and peer dependencies, including",
        "nested packages. It also includes every package measured by the current Vite build,",
        "including development dependencies actually bundled. Unbundled build tools are excluded.",
        "",
        "The Rust inventory includes every locked dependency, including build and target edges.",
        "Rust SPDX identifiers: " + ", ".join(sorted(RUST_ALLOWED_LICENSES)) + ".",
        "Rust also permits the exact Apache-2.0 WITH LLVM-exception expression: the upstream",
        "exception grants additional permissions for compiled artifacts. Other WITH terms fail.",
        "Rust has no package exceptions; unknown and missing licenses fail.",
        "",
        "Licenses are read from installed metadata and checked against exact locked versions.",
        "Ambiguous legacy metadata is accepted only with a reviewed license-file SHA-256 match.",
        "For python-dateutil, the verified BSD terms explicitly apply to all its code.",
        "",
        "Allowed SPDX identifiers: " + ", ".join(sorted(ALLOWED_LICENSES)) + ".",
        "Every term in a compound expression must be permitted; unknown or missing licenses fail.",
        "",
        "Approved exception: Python `certifi` uses `MPL-2.0` for root-certificate data only.",
        "Approved exception: Python `orjson` uses `MPL-2.0 AND (Apache-2.0 OR MIT)`.",
        "It is required by langsmith and langgraph-sdk; upstream source is distributed unchanged.",
        "Approved exception: Python `regex` uses `Apache-2.0 AND CNRI-Python`; CNRI-Python is",
        "permissive. These exact package exceptions do not permit other MPL or CNRI dependencies.",
        "Upstream license texts remain in",
        "installed distributions; frontend texts are in `web/public/THIRD-PARTY-LICENSES.txt`.",
        "Rust license texts and notices are retained in the extension wheel.",
        "",
        "| Ecosystem | Package | Version | SPDX license | Evidence |",
        "| --- | --- | --- | --- | --- |",
    ]
    lines.extend(
        f"| {item.ecosystem} | {item.name} | {item.version} | {item.license} | {item.evidence} |"
        for item in report.packages
    )
    lines.extend(["", f"Policy findings: {len(report.findings)}."])
    if report.findings:
        lines.extend(["", "The audit fails until every finding is resolved:", ""])
        lines.extend(f"- `{item.name}` {item.version}: {item.reason}." for item in report.findings)
    return "\n".join(lines) + "\n"


def main() -> None:
    """Write notices and an optional JSON report, returning nonzero on policy violations."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path)
    parser.add_argument("--json-report", type=Path)
    args = parser.parse_args()
    report = audit(args.root)
    output = args.output or args.root / "THIRD_PARTY_NOTICES.md"
    output.write_text(render_notices(report))
    if args.json_report:
        args.json_report.write_text(report.model_dump_json(indent=2) + "\n")
    console = Console()
    for item in report.packages:
        console.print(f"{item.ecosystem}: {item.name} {item.version}: {item.license}", markup=False)
    for finding in report.findings:
        console.print(f"FAIL {finding.name}: {finding.reason}", markup=False)
    console.print(f"Runtime packages: {len(report.packages)}; findings: {len(report.findings)}")
    raise SystemExit(bool(report.findings))


if __name__ == "__main__":
    main()
