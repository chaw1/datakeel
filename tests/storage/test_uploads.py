def declaration(content: bytes = b"abcdefghij", **changes: object) -> UploadInput:
    """Declare small generated bytes with deliberately uneven final chunk size."""
    return UploadInput.model_validate(
        {
            "idempotency_key": "generated-upload",
            "name": "Generated sample",
            "filename": "sample.txt",
            "total_bytes": len(content),
            "sha256": hashlib.sha256(content).hexdigest(),
            "chunk_bytes": 4,
            **changes,
        }
    )


def test_upload_resume_out_of_order_duplicate_and_publish(db: Database) -> None:
    """Reconnect sends just missing chunks; duplicate bytes and shuffled order are safe."""
    request = declaration()
    upload = start_upload(db, request)
    put_chunk(db, upload.id, 2, b"ij")
    assert get_upload(db, upload.id).missing_chunks == [0, 1]
    assert start_upload(db, request).id == upload.id
    put_chunk(db, upload.id, 0, b"abcd")
    assert put_chunk(db, upload.id, 0, b"abcd").received_chunks == [0, 2]
    put_chunk(db, upload.id, 1, b"efgh")
    completed = complete_upload(db, upload.id)
    assert completed.state == "COMPLETE"
    assert complete_upload(db, upload.id) == completed
    assert completed.dataset_id
    files = list_files(db, completed.dataset_id)
    assert files[0].sha256 == request.sha256
    assert files[0].size == 10
    with db.session() as session:
        assert session.scalar(select(func.count()).select_from(DatasetRow)) == 1
        assert session.scalar(select(func.count()).select_from(VersionRow)) == 1
    with pytest.raises(ConflictError, match="immutable"):
        put_chunk(db, upload.id, 0, b"abcd")


def test_conflicting_duplicate_preserves_original(db: Database) -> None:
    """A retry cannot silently replace a committed ordinal with different bytes."""
    upload = start_upload(db, declaration())
    put_chunk(db, upload.id, 0, b"abcd")
    with pytest.raises(ConflictError, match="different content"):
        put_chunk(db, upload.id, 0, b"xxxx")
    assert (upload_directory(upload.id) / "0").read_bytes() == b"abcd"


@pytest.mark.parametrize(("ordinal", "content"), [(2, b"ijkl"), (1, b"e"), (3, b""), (-1, b"abcd")])
def test_bad_chunk_size_and_ordinal_are_rejected(
    db: Database, ordinal: int, content: bytes
) -> None:
    """The final chunk has an exact size and no ordinal can extend the file."""
    upload = start_upload(db, declaration())
    with pytest.raises(ValidationError):
        put_chunk(db, upload.id, ordinal, content)
    assert get_upload(db, upload.id).received_chunks == []


def test_missing_chunk_and_hash_failure_never_publish(db: Database) -> None:
    """Complete rejects missing chunks and wrong whole-file hashes before facts are committed."""
    upload = start_upload(db, declaration(sha256="0" * 64))
    put_chunk(db, upload.id, 0, b"abcd")
    with pytest.raises(ValidationError, match="Missing"):
        complete_upload(db, upload.id)
    put_chunk(db, upload.id, 1, b"efgh")
    put_chunk(db, upload.id, 2, b"ij")
    with pytest.raises(ValidationError, match="Whole-file SHA-256"):
        complete_upload(db, upload.id)
    with db.session() as session:
        assert session.scalar(select(func.count()).select_from(DatasetRow)) == 0
        assert session.scalar(select(func.count()).select_from(VersionRow)) == 0
    assert get_upload(db, upload.id).state == "UPLOADING"


def test_empty_file_is_verified_and_published(db: Database) -> None:
    """An empty declared file needs no synthetic chunk and still has a verified digest."""
    upload = start_upload(db, declaration(b""))
    assert upload.missing_chunks == []
    assert complete_upload(db, upload.id).state == "COMPLETE"


def test_idempotency_declaration_conflict_and_unknown_upload(db: Database) -> None:
    """One caller key cannot be rebound; unknown IDs never create staging files."""
    start_upload(db, declaration())
    with pytest.raises(ConflictError, match="another declaration"):
        start_upload(db, declaration(filename="other.txt"))
    with pytest.raises(NotFoundError):
        get_upload(db, "unknown")
    with pytest.raises(NotFoundError):
        complete_upload(db, "unknown")
    with pytest.raises(NotFoundError):
        put_chunk(db, "../unknown", 0, b"abcd")


@pytest.mark.parametrize(
    "filename", ["../bad", "..", "a\\b", "/absolute", "nul\x00byte.txt", "é" * 128]
)
def test_upload_rejects_unsafe_filename(filename: str) -> None:
    """Names that no staging file system can hold are refused before any chunk is sent."""
    with pytest.raises(ModelValidationError):
        declaration(filename=filename)


def test_upload_rejects_excessive_chunks() -> None:
    """Tiny chunks cannot create an unbounded resume receipt."""
    with pytest.raises(ModelValidationError, match="larger chunk"):
        declaration(total_bytes=100_001, chunk_bytes=1)


def test_size_and_concurrency_limits(db: Database, monkeypatch: pytest.MonkeyPatch) -> None:
    """Configured bounds apply before publication and release slots after normal exits."""
    monkeypatch.setenv("DATAKEEL_UPLOAD_MAX_CHUNK_BYTES", "3")
    with pytest.raises(ValidationError, match="chunk size"):
        start_upload(db, declaration())
    monkeypatch.setenv("DATAKEEL_UPLOAD_MAX_CHUNK_BYTES", "4")
    monkeypatch.setenv("DATAKEEL_UPLOAD_MAX_FILE_BYTES", "9")
    with pytest.raises(ValidationError, match="file size"):
        start_upload(db, declaration())
    monkeypatch.setenv("DATAKEEL_UPLOAD_MAX_CONCURRENCY", "1")
    with (
        upload_slot(db),
        pytest.raises(ConflictError, match="concurrency limit"),
        upload_slot(db),
    ):
        pytest.fail("the second upload must not acquire a slot")
    with upload_slot(db):
        pass


def test_stored_object_corruption_rolls_back_dataset(
    db: Database, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A backend success response cannot publish an object whose actual bytes differ."""

    class CorruptStore(LocalStore):
        def put(self, path: Path, key: str) -> str:
            """Inject a backend that acknowledges a corrupted write."""
            result = super().put(path, key)
            self.materialize(key).write_bytes(b"corrupted!")
            return result

    store = CorruptStore(tmp_path / "corrupt")
    monkeypatch.setattr(datasets, "object_store", lambda: store)
    monkeypatch.setattr(upload_service, "object_store", lambda: store)
    upload = start_upload(db, declaration())
    for ordinal, content in enumerate((b"abcd", b"efgh", b"ij")):
        put_chunk(db, upload.id, ordinal, content)
    with pytest.raises(ValidationError, match="Stored object SHA-256"):
        complete_upload(db, upload.id)
    with db.session() as session:
        assert session.scalar(select(func.count()).select_from(DatasetRow)) == 0


def test_parallel_same_upload_merges_or_rejects_and_publishes_once(db: Database) -> None:
    """Two writers either merge identical chunks or return a retryable conflict."""
    upload = start_upload(db, declaration(b"abcd"))
    gate = Barrier(2)

    def concurrent_write(_index: int) -> str:
        gate.wait()
        try:
            put_chunk(db, upload.id, 0, b"abcd")
        except ConflictError:
            return "conflict"
        return "success"

    with ThreadPoolExecutor(max_workers=2) as executor:
        results = list(executor.map(concurrent_write, range(2)))
    assert "success" in results
    assert (upload_directory(upload.id) / "0").read_bytes() == b"abcd"
    receipt = complete_upload(db, upload.id)
    assert complete_upload(db, upload.id).dataset_id == receipt.dataset_id


def test_interrupted_temporary_does_not_count_as_received(db: Database) -> None:
    """A process interrupted before atomic rename leaves no false receipt."""
    upload = start_upload(db, declaration())
    directory = upload_directory(upload.id)
    directory.mkdir(parents=True)
    (directory / "temporary-incomplete").write_bytes(b"a")
    assert get_upload(db, upload.id).missing_chunks == [0, 1, 2]


def test_corrupted_chunk_is_rejected_on_completion(db: Database) -> None:
    """Final verification checks staging sizes even after an acknowledged chunk is damaged."""
    upload = start_upload(db, declaration(b"abcd"))
    put_chunk(db, upload.id, 0, b"abcd")
    path = upload_directory(upload.id) / "0"
    assert digest(path) == declaration(b"abcd").sha256
    path.write_bytes(b"a")
    with pytest.raises(ValidationError, match="incorrectly sized"):
        complete_upload(db, upload.id)


def test_s3_verification_bypasses_stale_cache(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """An acknowledged object must match fresh backend bytes even when cached bytes match."""
    content = b"abcd"
    monkeypatch.setenv("DATAKEEL_HOME", str(tmp_path / "home"))

    class Client:
        def download_file(self, _bucket: str, _key: str, filename: str) -> None:
            """Return the backend's actual corrupted bytes."""
            Path(filename).write_bytes(b"bad!")

    def client_factory(*_args: object, **_kwargs: object) -> Client:
        return Client()

    monkeypatch.setattr("datakeel.storage.objects.boto3.client", client_factory)
    store = S3Store("generated-bucket")
    store.cache.mkdir(parents=True)
    (store.cache / "sample").write_bytes(content)
    with pytest.raises(ValidationError, match="Stored object SHA-256"):
        verify_stored_object(store, "sample", declaration(content))


def test_missing_stored_object_never_publishes(
    db: Database, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A backend success without an actual object cannot create a committed dataset."""

    class MissingStore(LocalStore):
        def put(self, path: Path, key: str) -> str:
            """Acknowledge success without persisting any generated bytes."""
            return key

    store = MissingStore(tmp_path / "missing")
    monkeypatch.setattr(datasets, "object_store", lambda: store)
    monkeypatch.setattr(upload_service, "object_store", lambda: store)
    upload = start_upload(db, declaration(b"abcd"))
    put_chunk(db, upload.id, 0, b"abcd")
    with pytest.raises(ValidationError, match="Stored object is missing"):
        complete_upload(db, upload.id)
    with db.session() as session:
        assert session.scalar(select(func.count()).select_from(DatasetRow)) == 0


def test_idempotency_accepts_reordered_metadata_without_changing_types(db: Database) -> None:
    """Canonical identity ignores mapping order while preserving the immutable declaration."""
    first = declaration(metadata={"nested": {"count": 1, "active": True}, "title": "sample"})
    reordered = declaration(metadata={"title": "sample", "nested": {"active": True, "count": 1}})
    original = start_upload(db, first)
    assert start_upload(db, reordered).id == original.id


@pytest.mark.parametrize(("before", "after"), [(1, True), (0, False), (True, 1), (False, 0)])
def test_idempotency_refuses_numeric_boolean_metadata_rebinding(
    db: Database, *, before: int | bool, after: int | bool
) -> None:
    """JSON booleans and numbers remain distinct even when Python values compare equal."""
    start_upload(db, declaration(metadata={"count": before}))
    with pytest.raises(ConflictError, match="another declaration"):
        start_upload(db, declaration(metadata={"count": after}))
