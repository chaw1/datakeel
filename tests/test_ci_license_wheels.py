def _wheel(name: str, *, omit: str = "", identity: str = "") -> bytes:
    info = f"{name}-1.0.dist-info"
    files = {
        f"{name}.py": b'"""Generated fixture."""\n',
        f"{info}/METADATA": (
            f"Metadata-Version: 2.4\nName: {identity or name}\nVersion: 1.0\n"
            f"License-Expression: MPL-2.0\nProject-URL: Source, https://example.org/{name}\n"
        ).encode(),
        f"{info}/WHEEL": b"Wheel-Version: 1.0\nRoot-Is-Purelib: true\nTag: py3-none-any\n",
        f"{info}/LICENSE": b"Generated license notice\n",
    }
    rows: list[str] = []
    for path, payload in files.items():
        digest = base64.urlsafe_b64encode(hashlib.sha256(payload).digest()).rstrip(b"=")
        rows.append(f"{path},sha256={digest.decode()},{len(payload)}")
    files[f"{info}/RECORD"] = ("\n".join([*rows, f"{info}/RECORD,,"]) + "\n").encode()
    if omit == "invalid-wheel":
        files[f"{info}/WHEEL"] = b"not wheel metadata\n"
    elif omit == "invalid-tag":
        files[f"{info}/WHEEL"] = b"Wheel-Version: 1.0\nRoot-Is-Purelib: true\nTag: invalid\n"
    elif omit == "empty-record":
        files[f"{info}/RECORD"] = b""
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, "w") as archive:
        for path, payload in files.items():
            if path != f"{info}/{omit}":
                archive.writestr(path, payload)
    return stream.getvalue()


def _lock(root: Path, payloads: dict[str, bytes]) -> Path:
    rows = [
        (
            '[[package]]\nname="application"\nversion="1"\nsource={editable="."}\n'
            'dependencies=[{name="certifi"},{name="orjson"}]\n'
        ),
        '[[package]]\nname="unrequested"\nversion="1"\nsource={registry="https://pypi.org/simple"}',
    ]
    for name, payload in payloads.items():
        rows.append(
            f'[[package]]\nname="{name}"\nversion="1.0"\n'
            'source={registry="https://pypi.org/simple"}\n'
            f'wheels=[{{url="{_PREFIX}{name}-1.0-py3-none-any.whl",'
            f'hash="sha256:{hashlib.sha256(payload).hexdigest()}",size={len(payload)}}}]'
        )
    path = root / "uv.lock"
    path.write_text("\n".join(rows) + "\n")
    return path


@pytest.fixture
def payloads() -> dict[str, bytes]:
    """Create two tiny upstream archives entirely from generated bytes."""
    return {name: _wheel(name) for name in ("certifi", "orjson")}


def _transport(payloads: dict[str, bytes], requests: list[str]) -> httpx.MockTransport:
    def handle(request: httpx.Request) -> httpx.Response:
        requests.append(str(request.url))
        assert request.headers["accept-encoding"] == "identity"
        name = request.url.path.rsplit("/", 1)[-1].split("-")[0]
        return httpx.Response(200, content=payloads[name])

    return httpx.MockTransport(handle)


def _client(payloads: dict[str, bytes], requests: list[str]) -> httpx.Client:
    return httpx.Client(transport=_transport(payloads, requests), trust_env=False)


def test_supply_downloads_only_exact_targets_and_reuses_verified_directory(
    tmp_path: Path, payloads: dict[str, bytes]
) -> None:
    """Downloads use literal lock URLs; validated existing originals need no further requests."""
    lock = _lock(tmp_path, payloads)
    requests: list[str] = []
    store = tmp_path / "wheels"
    with _client(payloads, requests) as client:
        paths = supply_wheels(lock, store, client)
        assert supply_wheels(lock, store, client) == paths
    assert requests == [pin.artifact.url for pin in locked_wheels(lock)]
    assert sorted(p.name for p in store.iterdir()) == sorted(p.name for p in paths)
    assert [p.read_bytes() for p in paths] == list(payloads.values())


@pytest.mark.parametrize(
    ("before", "after"),
    [
        ("https://files.pythonhosted.org", "http://files.pythonhosted.org"),
        ("files.pythonhosted.org", "example.org"),
        ("files.pythonhosted.org", "files.pythonhosted.org.example.org"),
        ("files.pythonhosted.org", "files.pythonhosted.org@fixture.invalid"),
        ("files.pythonhosted.org", "files.pythonhosted.org:443"),
        (".whl", ".whl?download=1"),
        (".whl", ".whl#fragment"),
        (".whl", ".tar.gz"),
        ("files.pythonhosted.org", "files.pythonhosted.org "),
        ("certifi-1.0-", "certifi%2d1.0-"),
        ("/packages/aa/bb/cccc/", "/packages/aa/bb/../"),
        ("certifi-1.0-", "different-1.0-"),
        ("certifi-1.0-", "certifi-2.0-"),
        ('hash="sha256:', 'hash="sha512:'),
        ('hash="sha256:', 'hash="sha256:X'),
        (",size=", ",missing_size="),
        ("https://pypi.org/simple", "https://example.org/simple"),
        ('name="orjson"', 'name="other"'),
    ],
)
def test_invalid_lock_rejected_before_requests(
    tmp_path: Path, payloads: dict[str, bytes], before: str, after: str
) -> None:
    """Invalid URLs, package identities and missing or malformed pins never start a download."""
    lock = _lock(tmp_path, payloads)
    lock.write_text(lock.read_text().replace(before, after))
    requests: list[str] = []
    with (
        _client(payloads, requests) as client,
        pytest.raises((ValidationError, ModelValidationError, ValueError)),
    ):
        supply_wheels(lock, tmp_path / "wheels", client)
    assert requests == []


