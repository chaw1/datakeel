@pytest.mark.parametrize("symlink", [False, True])
def test_corrupt_existing_evidence_is_not_replaced_from_network(
    tmp_path: Path, payloads: dict[str, bytes], *, symlink: bool
) -> None:
    """Reusing a directory requires original regular files with the same byte pins."""
    lock = _lock(tmp_path, payloads)
    store = tmp_path / "wheels"
    store.mkdir()
    path = store / locked_wheels(lock)[0].filename
    if symlink:
        target = tmp_path / "original.whl"
        target.write_bytes(payloads["certifi"])
        path.symlink_to(target)
    else:
        path.write_bytes(b"corrupt")
    requests: list[str] = []
    with _client(payloads, requests) as client, pytest.raises(ValidationError):
        supply_wheels(lock, store, client)
    assert requests == []


def _python_notices(root: Path, monkeypatch: pytest.MonkeyPatch) -> str:
    def distribution(name: str) -> PathDistribution:
        return PathDistribution(root / "site" / f"{name}-1.0.dist-info")

    monkeypatch.setattr(license_python.metadata, "distribution", distribution)
    packages = license_python.python_packages(root)
    report = LicenseReport(
        python_target="generated",
        packages=packages,
        findings=tuple(f for package in packages for f in license_findings(package)),
    )
    assert not report.findings
    return render_notices(report)


def test_main_exports_only_after_validation_and_reuse_keeps_notices(
    tmp_path: Path, payloads: dict[str, bytes], monkeypatch: pytest.MonkeyPatch
) -> None:
    """Setup exports a reusable directory; the offline audit renders identical notices."""
    lock = _lock(tmp_path, payloads)
    (tmp_path / "pyproject.toml").write_text(
        '[project]\nname="application"\ndependencies=["certifi==1.0","orjson==1.0"]\n'
    )
    for payload in payloads.values():
        with zipfile.ZipFile(io.BytesIO(payload)) as archive:
            for member in archive.namelist():
                path = tmp_path / "site" / member
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(archive.read(member))
    requests: list[str] = []
    factory: Callable[..., httpx.Client] = httpx.Client

    def client(**kwargs: object) -> httpx.Client:
        assert kwargs == {"trust_env": False, "follow_redirects": False, "timeout": 30}
        return factory(transport=_transport(payloads, requests))

    monkeypatch.setattr(ci_license_wheels.httpx, "Client", client)
    store = tmp_path / "wheels"
    environment = tmp_path / "github-env"
    environment.write_text("EXISTING=value\n")
    monkeypatch.setattr(
        sys,
        "argv",
        [
            "ci_license_wheels",
            "--lock",
            str(lock),
            "--wheel-dir",
            str(store),
            "--github-env",
            str(environment),
        ],
    )
    ci_license_wheels.main()
    assert environment.read_text() == f"EXISTING=value\nDATAKEEL_LICENSE_WHEEL_DIR={store}\n"
    monkeypatch.setenv("DATAKEEL_LICENSE_WHEEL_DIR", str(store))
    before = _python_notices(tmp_path, monkeypatch)
    ci_license_wheels.main()
    assert len(requests) == 2
    assert _python_notices(tmp_path, monkeypatch) == before
    (store / locked_wheels(lock)[0].filename).write_bytes(b"corrupt")
    exported = environment.read_bytes()
    with pytest.raises(ValidationError):
        ci_license_wheels.main()
    assert environment.read_bytes() == exported


