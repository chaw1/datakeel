def test_duplicate_target_or_incompatible_wheels_rejected(
    tmp_path: Path, payloads: dict[str, bytes], monkeypatch: pytest.MonkeyPatch
) -> None:
    """Ambiguous package entries and source-only platforms cannot silently use another artifact."""
    lock = _lock(tmp_path, payloads)
    original = lock.read_text()
    lock.write_text(original + original[original.index('[[package]]\nname="orjson"') :])
    with pytest.raises(ValidationError, match="one locked"):
        locked_wheels(lock)
    lock.write_text(original)
    monkeypatch.setattr(ci_license_wheels, "sys_tags", lambda: iter([Tag("cp999", "none", "any")]))
    with pytest.raises(ValidationError, match="No compatible"):
        locked_wheels(lock)


@pytest.mark.parametrize("status", [301, 302, 303, 307, 308, 404, 500, 204, 206])
@pytest.mark.parametrize(
    "location",
    [
        _PREFIX + "certifi-1.0-py3-none-any.whl",
        _PREFIX + "other.whl",
        "https://example.org/other.whl",
    ],
)
def test_redirect_and_error_responses_never_followed(
    tmp_path: Path, payloads: dict[str, bytes], status: int, location: str
) -> None:
    """Even a locked-host redirect fails, regardless of a client's redirect default."""
    lock = _lock(tmp_path, payloads)
    requests: list[str] = []

    def handle(request: httpx.Request) -> httpx.Response:
        requests.append(str(request.url))
        return httpx.Response(status, headers={"location": location})

    with (
        httpx.Client(transport=httpx.MockTransport(handle), follow_redirects=True) as client,
        pytest.raises((httpx.HTTPStatusError, ValidationError)),
    ):
        supply_wheels(lock, tmp_path / "wheels", client)
    assert requests == [locked_wheels(lock)[0].artifact.url]
    assert list((tmp_path / "wheels").iterdir()) == []


@pytest.mark.parametrize("attack", ["hash", "truncated", "oversized", "length-header", "encoding"])
def test_bad_response_bytes_fail_without_publishing_partial_evidence(
    tmp_path: Path, payloads: dict[str, bytes], attack: str
) -> None:
    """A failure on the second target removes the first staged file and blocks all supply."""
    lock = _lock(tmp_path, payloads)

    def handle(request: httpx.Request) -> httpx.Response:
        payload = payloads["certifi" if "certifi-" in request.url.path else "orjson"]
        headers: dict[str, str] = {}
        if "orjson-" in request.url.path:
            if attack == "hash":
                payload = b"X" + payload[1:]
            elif attack == "truncated":
                payload = payload[:-1]
            elif attack == "oversized":
                payload += b"X"
            elif attack == "length-header":
                headers["content-length"] = "1"
            else:
                headers["content-encoding"] = "identity, identity"
        return httpx.Response(200, content=payload, headers=headers)

    with (
        httpx.Client(transport=httpx.MockTransport(handle)) as client,
        pytest.raises(ValidationError),
    ):
        supply_wheels(lock, tmp_path / "wheels", client)
    assert list((tmp_path / "wheels").iterdir()) == []


@pytest.mark.parametrize(
    "attack",
    [
        "html",
        "zip",
        "metadata",
        "WHEEL",
        "RECORD",
        "invalid-wheel",
        "invalid-tag",
        "empty-record",
    ],
)
def test_hash_pinned_non_wheel_or_wrong_metadata_rejected(
    tmp_path: Path, payloads: dict[str, bytes], attack: str
) -> None:
    """A matching hash and length cannot turn HTML or an arbitrary ZIP into valid evidence."""
    if attack == "html":
        payloads["orjson"] = b"<html>not a wheel</html>"
    elif attack == "zip":
        stream = io.BytesIO()
        with zipfile.ZipFile(stream, "w") as archive:
            archive.writestr("file.txt", "generated")
        payloads["orjson"] = stream.getvalue()
    else:
        payloads["orjson"] = _wheel(
            "orjson", omit=attack, identity="wrong" if attack == "metadata" else ""
        )
    lock = _lock(tmp_path, payloads)
    with _client(payloads, []) as client, pytest.raises((ValidationError, ValueError)):
        supply_wheels(lock, tmp_path / "wheels", client)
    assert list((tmp_path / "wheels").iterdir()) == []


@pytest.mark.parametrize("attack", ["truncated", "oversized", "read-error"])
def test_stream_without_length_header_fails_closed(
    tmp_path: Path, payloads: dict[str, bytes], attack: str
) -> None:
    """Actual streamed lengths and interrupted transfers fail even without an HTTP byte count."""
    lock = _lock(tmp_path, payloads)

    class Stream(httpx.SyncByteStream):
        def __iter__(self) -> Iterator[bytes]:
            payload = payloads["certifi"]
            yield payload[:-1]
            if attack == "read-error":
                msg = "Generated interrupted transfer"
                raise httpx.ReadError(msg)
            if attack == "oversized":
                yield payload[-1:] + b"X"

    def handle(_request: httpx.Request) -> httpx.Response:
        return httpx.Response(200, stream=Stream())

    with (
        httpx.Client(transport=httpx.MockTransport(handle)) as client,
        pytest.raises((ValidationError, httpx.ReadError)),
    ):
        supply_wheels(lock, tmp_path / "wheels", client)
    assert list((tmp_path / "wheels").iterdir()) == []


@pytest.mark.parametrize("pin", ["hash", "size"])
def test_validly_formatted_wrong_pin_rejected(
    tmp_path: Path, payloads: dict[str, bytes], pin: str
) -> None:
    """Well-formed but incorrect integrity pins still reject genuine wheel responses."""
    lock = _lock(tmp_path, payloads)
    original = lock.read_text()
    if pin == "hash":
        original = original.replace(hashlib.sha256(payloads["certifi"]).hexdigest(), "0" * 64)
    else:
        original = original.replace(f"size={len(payloads['certifi'])}", "size=1")
    lock.write_text(original)
    with _client(payloads, []) as client, pytest.raises(ValidationError):
        supply_wheels(lock, tmp_path / "wheels", client)


