@pytest.mark.parametrize(("question", "intent"), [*_TOPIC, *_COUNTERFACTUAL, *_FLOW, *_PASSIVE])
def test_long_tail_roles_preserve_the_requested_argument(question: str, intent: str) -> None:
    """Both sides of each construction use the same registered source identity."""
    parsed = registered_question(question, "inventory")
    assert parsed is not None
    assert parsed.intent == intent
    assert parsed.intent_candidates == ()
    assert len(parsed.candidates) == 1
    assert parsed.candidates[0].name == "inventory"
    assert all("§" not in word for word in parsed.recognition.direction_text)


@pytest.mark.parametrize(
    "question",
    [
        "退款额有谁在使用?",
        "退款额停掉以后\uff0c哪些表会受影响?",
        "Where does inventory_units end up?",
        "Who is inventory_units consumed by?",
    ],
)
def test_metric_subject_dependency_remains_knowledge(question: str) -> None:
    """A metric identity never turns a request for its consumer into a numeric answer."""
    subject = "退款额" if "退款额" in question else "inventory_units"
    parsed = registered_question(question, subject)
    assert parsed is not None
    assert parsed.intent == "downstream"


def test_flow_preposition_and_interrogative_slots_cannot_be_reversed() -> None:
    """A flipped destination slot or a lost source preposition must fail the same identity."""
    for question, expected in (
        ("Where does inventory end up?", "downstream"),
        ("What ends up in inventory?", "upstream"),
        ("What flows from inventory?", "downstream"),
        ("Where does inventory flow from?", "upstream"),
    ):
        parsed = registered_question(question, "inventory")
        assert parsed is not None
        assert parsed.intent == expected
        assert parsed.recognition.rule_id == "K17-flow-slot"
