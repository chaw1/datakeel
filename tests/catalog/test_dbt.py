def test_same_table_when_model_and_source_overlap_prefers_informative_model() -> None:
    """Keep modeled descriptions and owner while preserving source tags and aliases."""
    request = _request(
        {
            "model.shop.orders": _node(
                "model.shop.orders",
                description="Modeled orders",
                config={"materialized": "view"},
                meta={"owner": "Finance"},
                tags=["modeled"],
                columns={
                    "amount": {
                        "name": "amount",
                        "description": "Modeled amount",
                        "data_type": "DOUBLE",
                    }
                },
            )
        },
        sources={
            "source.shop.orders": _node(
                "source.shop.orders",
                description="Raw orders",
                meta={"owner": "Operations"},
                tags=["raw"],
                columns={"amount": {"name": "amount", "description": "Raw amount"}},
            )
        },
    )
    objects = _objects(request)
    table = objects["shop/main/orders"]
    assert table.properties.root["is_view"] is True
    assert _metadata(table).description == "Modeled orders"
    assert _metadata(table).owner == "Finance"
    assert _metadata(table).tags == ("modeled", "raw")
    assert objects["shop/main/orders/amount"].properties.root["comment"] == "Modeled amount"
    assert objects["shop/main/orders/amount"].properties.root["data_type"] == "DOUBLE"


def test_catalog_when_warehouse_folds_case_matches_declared_column_description() -> None:
    """Join unambiguous warehouse field spelling to manifest docs without duplicate fields."""
    request = _request(
        {
            "model.shop.orders": _node(
                "model.shop.orders",
                columns={"amount": {"name": "amount", "description": "Revenue"}},
            )
        }
    )
    request = request.model_copy(
        update={
            "catalog": JsonDocument(
                {
                    "nodes": {
                        "model.shop.orders": {
                            "columns": {"AMOUNT": {"name": "AMOUNT", "type": "DOUBLE"}}
                        },
                    }
                }
            )
        }
    )
    objects = _objects(request)
    assert "shop/main/orders/amount" not in objects
    assert objects["shop/main/orders/AMOUNT"].properties.root["comment"] == "Revenue"
    assert objects["shop/main/orders/AMOUNT"].properties.root["data_type"] == "DOUBLE"


def test_manifest_when_case_sensitive_fields_are_distinct_preserves_both() -> None:
    """Do not coalesce genuinely distinct quoted column names while matching warehouse case."""
