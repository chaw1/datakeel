_FIXTURES = Path(__file__).parents[1] / "fixtures" / "dbt"


@pytest.fixture
def dbt_request() -> DbtImportRequest:
    """Load sanitized artifacts generated by an actual isolated dbt build."""
    return DbtImportRequest(
        source_id="shop",
        name="Fictional shop",
        manifest=JsonDocument.model_validate_json((_FIXTURES / "manifest.json").read_text()),
        catalog=JsonDocument.model_validate_json((_FIXTURES / "catalog.json").read_text()),
        run_results=JsonDocument.model_validate_json((_FIXTURES / "run_results.json").read_text()),
    )


def _node(identity: str, name: str = "orders", **fields: JsonValue) -> dict[str, JsonValue]:
    return {
        "unique_id": identity,
        "name": name,
        "resource_type": identity.split(".", maxsplit=1)[0],
        "schema": "main",
        **fields,
    }


def _request(
    nodes: dict[str, JsonValue],
    *,
    sources: dict[str, JsonValue] | None = None,
    version: int = 12,
) -> DbtImportRequest:
    return DbtImportRequest(
        source_id="shop",
        manifest=JsonDocument(
            {
                "metadata": {
                    "dbt_schema_version": f"https://schemas.getdbt.com/dbt/manifest/v{version}.json",
                    "adapter_type": "duckdb",
                },
                "nodes": nodes,
                "sources": sources or {},
            }
        ),
    )


def _metadata(item: CatalogObject) -> ExternalMetadata:
    return ExternalMetadata.model_validate(item.properties.root["integration"])


def _objects(request: DbtImportRequest) -> dict[str, CatalogObject]:
    return {item.asset_ref.asset_id: item for item in prepare_dbt(request).snapshot.objects}


def test_real_artifacts_when_imported_preserve_physical_tables_and_descriptions(
    dbt_request: DbtImportRequest,
) -> None:
    """Resolve quoted aliases and retain declared table, column, ownership, and tags."""
    objects = _objects(dbt_request)
    assert {item.name for item in objects.values() if item.asset_ref.asset_type == "table"} == {
        "Orders Daily",
        "raw_orders",
        "order_history",
        "metricflow_time_spine",
    }
    table = objects["shop/main/Orders%20Daily"]
    assert table.properties.root["comment"] == "Daily fictional orders"
    assert table.properties.root["is_view"] is True
    assert _metadata(table).owner == "Finance"
    assert _metadata(table).tags == ("finance",)
    column = objects["shop/main/Orders%20Daily/amount"]
    assert column.properties.root["comment"] == "Revenue amount"
    assert column.properties.root["data_type"] == "DOUBLE"
    assert _metadata(table).relation is not None
    assert _metadata(table).relation.database == "shop"


def test_real_artifacts_when_seed_is_also_source_coalesce_aliases_and_quality(
    dbt_request: DbtImportRequest,
) -> None:
    """Represent the physical table once while preserving both stable dbt identities."""
    objects = _objects(dbt_request)
    table = objects["shop/main/raw_orders"]
    metadata = _metadata(table)
    assert metadata.details.root["resource_aliases"] == [
        "seed.p22_shop.raw_orders",
        "source.p22_shop.shop.orders",
    ]
    assert metadata.owner == "Operations"
    tests = metadata.details.root["tests"]
    assert isinstance(tests, list)
    assert len(tests) == 1
    assert isinstance(tests[0], dict)
    assert tests[0]["result"]["status"] == "pass"
    assert metadata.description == "Raw fictional orders"


def test_real_artifacts_when_compiled_prove_table_and_column_lineage(
    dbt_request: DbtImportRequest,
) -> None:
    """Read depends_on at table level and use SQL provenance for actual field edges."""
    batch = prepare_dbt(dbt_request)
    edges = {
        (link.source.asset_id, link.target.asset_id)
        for link in batch.snapshot.links
        if link.kind == "derived"
    }
    assert not batch.parse_failures
    assert ("shop/main/raw_orders", "shop/main/Orders%20Daily") in edges
    assert ("shop/main/raw_orders", "shop/history/order_history") in edges
    assert ("shop/main/raw_orders/amount", "shop/history/order_history/amount") in edges
    assert ("shop/main/raw_orders/amount", "shop/main/Orders%20Daily/amount") in edges
    assert len([edge for edge in edges if "/Orders%20Daily/" in edge[1]]) == 4


def test_real_artifacts_when_exposure_imported_connect_consumer_and_owner(
    dbt_request: DbtImportRequest,
) -> None:
    """Keep exposure consumers and explicit ownership usable by catalog traversal."""
    snapshot = prepare_dbt(dbt_request).snapshot
    exposure = next(item for item in snapshot.objects if item.asset_ref.asset_type == "exposure")
    assert _metadata(exposure).owner == "Reporting"
    assert _metadata(exposure).description == "Finance revenue dashboard"
    assert any(
        link.source.asset_id == "shop/main/Orders%20Daily" and link.target == exposure.asset_ref
        for link in snapshot.links
    )
    assert any(
        link.source == exposure.asset_ref
        and link.kind == "owned_by"
        and link.target.display_name == "Reporting"
        for link in snapshot.links
    )


def test_real_artifacts_when_tests_ran_keep_definitions_and_latest_results(
    dbt_request: DbtImportRequest,
) -> None:
    """Store test SQL and results on the table and its tested column."""
    objects = _objects(dbt_request)
    metadata = _metadata(objects["shop/main/Orders%20Daily"])
    tests = metadata.details.root["tests"]
    assert isinstance(tests, list)
    assert len(tests) == 2
    for test in tests:
        assert isinstance(test, dict)
        assert test["definition"]["compiled_code"]
        assert test["result"]["status"] == "pass"
        assert test["result"]["failures"] == 0
    column_tests = _metadata(objects["shop/main/Orders%20Daily/order_id"]).details.root["tests"]
    assert column_tests == tests


def test_real_artifacts_when_semantics_imported_create_only_unconfirmed_drafts(
    dbt_request: DbtImportRequest,
) -> None:
    """Retain raw semantic declarations and safely map only the simple supported metric."""
    objects = _objects(dbt_request)
    assert not any(item.asset_ref.asset_type == "metric" for item in objects.values())
    drafts = [
        MetricDraft.model_validate(item.properties.root)
        for item in objects.values()
        if item.asset_ref.asset_type == "metric_draft"
    ]
    assert len(drafts) == 2
    assert all(draft.status == "draft" for draft in drafts)
    metric = next(draft for draft in drafts if draft.unique_id.startswith("metric."))
    assert metric.raw.root["type"] == "simple"
    assert metric.definition is not None
    assert metric.definition.measure.table == "shop/main/Orders%20Daily"
    assert metric.definition.measure.column == "shop/main/Orders%20Daily/amount"
    assert metric.definition.time.column == "shop/main/Orders%20Daily/ordered_at"


