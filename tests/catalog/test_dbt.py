@pytest.mark.parametrize(
    ("relation", "expected"),
    [
        ('"warehouse"."Mixed.Schema"."Order /%"', "shop/Mixed.Schema/Order%20%2F%25"),
        ('"main"."different_alias"', "shop/main/different_alias"),
        ('"one.table"', "shop/main/one.table"),
    ],
)
def test_relation_when_quoted_uses_parser_instead_of_splitting_dots(
    relation: str, expected: str
) -> None:
    """Preserve literal dots, spaces, escaped path delimiters, and physical aliases."""
    request = _request({"model.shop.logical": _node("model.shop.logical", relation_name=relation)})
    assert expected in _objects(request)


def test_relation_when_absent_uses_source_identifier_and_model_alias() -> None:
    """Use the documented fallback fields for artifacts that precede compilation."""
    request = _request(
        {"model.shop.logical": _node("model.shop.logical", alias="actual_model")},
        sources={"source.shop.raw": _node("source.shop.raw", identifier="actual_source")},
    )
    assert {"shop/main/actual_model", "shop/main/actual_source"} <= _objects(request).keys()


