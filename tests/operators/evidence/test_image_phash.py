"""Image hashing measures actual source bytes and retains corrupt evidence."""

from pathlib import Path

import pytest

from datakeel.core.evidence_models import EvidenceValue, Whole
from datakeel.core.models import FileItem
from tests.operators.evidence.helpers import drafts, run_node


def test_image_phash_when_valid_reports_64_bits_and_measured_absence(
    sample: FileItem, tmp_path: Path
) -> None:
    """Verify successful decoding produces a versioned Whole corruption observation."""
    result = run_node("image_phash", sample, tmp_path)
    draft = drafts(result)[0]
    assert len(result.metadata["image_phash"]) == 16
    assert result.metadata["image_dimensions"] == {"width": 192, "height": 128}
    assert not result.metadata["evidence_failed"]
    assert draft.object == EvidenceValue(value="absent")
    assert isinstance(draft.anchors[0].selector, Whole)
    assert draft.anchors[0].content_revision == sample.sha256


def test_image_phash_when_corrupt_retains_source_and_present_observation(
    sample: FileItem, tmp_path: Path
) -> None:
    """Verify corrupt inputs are observable rather than silently filtered away."""
    Path(sample.path).write_bytes(b"deliberately corrupt generated bytes")
    result = run_node("image_phash", sample, tmp_path)
    assert result.id == sample.id
    assert result.metadata["image_phash"] is None
    assert result.metadata["evidence_failed"]
    assert drafts(result)[0].object == EvidenceValue(value="present")
    assert drafts(result)[0].anchors[0].content_revision != sample.sha256


def test_image_phash_when_image_exceeds_limits_marks_failure(
    sample: FileItem, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Verify bounded image decoding applies to evidence hashing as well."""
    monkeypatch.setattr("datakeel.operators.image.helpers.MAX_IMAGE_BYTES", 1)
    assert run_node("image_phash", sample, tmp_path).metadata["evidence_failed"]
